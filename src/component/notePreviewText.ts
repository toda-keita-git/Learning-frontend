// メモ一覧のカードに出す、本文の抜粋テキストを作る。
//
// 以前は本文をそのまま流し込んでいたため、`# 見出し` や `**太字**` の記号が
// そのまま見えていた。とくに問題だったのが穴埋め記法で、`[[ ]]` の中身は
// 復習で当てさせたい答えそのものなのに、一覧を眺めるだけで見えてしまい、
// 復習機能が成立しなくなっていた。
//
// ここではMarkdownを描画するのではなく、記号だけを取り除いた素のテキストにする。
// カードは3行で切り詰める前提なので、見出しの大小や強調を再現する必要はない。

// 穴埋め `[[答え]]` の伏字。一覧で答えが見えないようにしつつ、そこに何かあることは示す。
// アンダースコアは使わない（この後の斜体 `_..._` を外す処理に巻き込まれて消えるため）
const CLOZE_MASK = "［伏字］";

export const notePreviewText = (body: string): string =>
  body
    // コードブロックは中身を出さず、そこにコードがあることだけ示す
    .replace(/```[\s\S]*?```/g, "［コード］")
    .replace(/`([^`]+)`/g, "$1")
    // 穴埋めは答えを伏せる（復習前にカードで答えが見えてしまうのを防ぐ）
    .replace(/\[\[([^\]]+)\]\]/g, CLOZE_MASK)
    // 画像・リンクは表示テキストだけ残す
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    // 見出し・引用・箇条書き・番号付きリストの行頭記号
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")
    .replace(/^\s{0,3}>\s?/gm, "")
    .replace(/^\s{0,3}[-*+]\s+/gm, "")
    .replace(/^\s{0,3}\d+\.\s+/gm, "")
    // 水平線
    .replace(/^\s{0,3}([-*_])\s*(\1\s*){2,}$/gm, "")
    // 強調・取り消し線・ハイライト。
    // アンダースコアは単語の途中にある場合は強調として扱わない（CommonMarkと同じ規則）。
    // これをやらないと `user_id` が「userid」、`MAX_BAR_LANES` が「MAXBARLANES」に
    // なってしまう。プログラミングの学習メモでは識別子が頻出するため実害が大きい。
    // 前側は後読みを使わず捕捉グループで見る（後読みはSafari 16.3以前で動かないため）
    .replace(/(\*\*)(.*?)\1/g, "$2")
    .replace(/(^|[^\w])__(.+?)__(?!\w)/g, "$1$2")
    .replace(/(\*)(.*?)\1/g, "$2")
    .replace(/(^|[^\w])_(.+?)_(?!\w)/g, "$1$2")
    .replace(/~~(.*?)~~/g, "$1")
    .replace(/==(.*?)==/g, "$1")
    // 記号を外したことで生まれた空行をまとめる
    .replace(/\n{3,}/g, "\n\n")
    .trim();
